def text_width(text, font, scale=1, spacing=1):
    if not text:
        return 0
    glyph_w = len(next(iter(font.values()))[0])
    return len(text) * (glyph_w * scale + spacing) - spacing


def draw_text(px, x, y, text, color, font, scale=1, spacing=1, W=64, H=64):
    """Blit text into a {(x,y): (r,g,b)} pixel dict. Returns the x
    position just past the last glyph."""
    glyph_w = len(next(iter(font.values()))[0])
    for ch in text.upper():
        glyph = font.get(ch)
        if glyph is None:
            x += glyph_w * scale + spacing
            continue
        for ry, row in enumerate(glyph):
            for rx, bit in enumerate(row):
                if bit != "1":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        pxx = x + rx * scale + sx
                        pyy = y + ry * scale + sy
                        if 0 <= pxx < W and 0 <= pyy < H:
                            px[(pxx, pyy)] = color
        x += glyph_w * scale + spacing
    return x


def draw_sprite(px, x, y, rows, color, W=64, H=64, color2=(255, 255, 255)):
    """Blit a sprite. '1' pixels take `color`, '2' pixels take `color2`
    (used for the football's laces)."""
    for ry, row in enumerate(rows):
        for rx, bit in enumerate(row):
            if bit == "0":
                continue
            if 0 <= x + rx < W and 0 <= y + ry < H:
                px[(x + rx, y + ry)] = color if bit == "1" else color2
